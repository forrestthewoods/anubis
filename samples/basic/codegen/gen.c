/* A tiny code generator: turns a text file into a C function returning it.
 * Usage: gen <input> <output.c> <function name> */
#include <stdio.h>

int main(int argc, char** argv) {
    if (argc != 4) {
        fprintf(stderr, "usage: gen <input> <output.c> <function name>\n");
        return 2;
    }
    FILE* in = fopen(argv[1], "rb");
    if (!in) {
        fprintf(stderr, "gen: cannot open %s\n", argv[1]);
        return 1;
    }
    FILE* out = fopen(argv[2], "wb");
    if (!out) {
        fprintf(stderr, "gen: cannot write %s\n", argv[2]);
        fclose(in);
        return 1;
    }
    fprintf(out, "/* Generated by //samples/basic/codegen:gen. Do not edit. */\n");
    fprintf(out, "const char* %s(void) {\n    static const char text[] = {", argv[3]);
    int c;
    int n = 0;
    while ((c = fgetc(in)) != EOF) {
        if (c == '\r') {
            continue; /* the same output from a CRLF checkout */
        }
        fprintf(out, "%s%d,", (n++ % 16) ? " " : "\n        ", c);
    }
    fprintf(out, "\n        0\n    };\n    return text;\n}\n");
    fclose(in);
    return fclose(out) == 0 ? 0 : 1;
}
